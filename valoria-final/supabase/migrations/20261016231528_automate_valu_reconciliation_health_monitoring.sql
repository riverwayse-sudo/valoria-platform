-- Provide a service-role-only Data API wrapper and retain aggregate monitoring snapshots.
-- No participant names, emails, account IDs, or raw evidence are stored in this telemetry.
CREATE TABLE IF NOT EXISTS private.valu_reconciliation_health_snapshots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  generated_at timestamptz NOT NULL,
  recorded_at timestamptz NOT NULL DEFAULT now(),
  health jsonb NOT NULL,
  alert_keys text[] NOT NULL DEFAULT ARRAY[]::text[]
);

ALTER TABLE private.valu_reconciliation_health_snapshots ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE private.valu_reconciliation_health_snapshots FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON TABLE private.valu_reconciliation_health_snapshots TO service_role;
CREATE INDEX IF NOT EXISTS idx_valu_reconciliation_health_snapshots_recorded_at
  ON private.valu_reconciliation_health_snapshots (recorded_at DESC);

CREATE OR REPLACE FUNCTION public.run_valu_reconciliation_health()
RETURNS jsonb
LANGUAGE sql
SECURITY DEFINER
SET search_path = ''
AS $function$
  SELECT private.valu_reconciliation_health();
$function$;

REVOKE ALL ON FUNCTION public.run_valu_reconciliation_health() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.run_valu_reconciliation_health() TO service_role;

CREATE OR REPLACE FUNCTION public.record_valu_reconciliation_health_snapshot(
  p_health jsonb,
  p_alert_keys text[] DEFAULT ARRAY[]::text[]
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  snapshot_id bigint;
  recorded timestamptz;
BEGIN
  IF p_health IS NULL OR jsonb_typeof(p_health) IS DISTINCT FROM 'object' THEN
    RAISE EXCEPTION 'A health report object is required.' USING ERRCODE = '22023';
  END IF;

  INSERT INTO private.valu_reconciliation_health_snapshots (generated_at, health, alert_keys)
  VALUES (
    coalesce((p_health ->> 'generated_at')::timestamptz, now()),
    p_health,
    coalesce(p_alert_keys, ARRAY[]::text[])
  )
  RETURNING id, recorded_at INTO snapshot_id, recorded;

  RETURN jsonb_build_object(
    'id', snapshot_id,
    'recorded_at', recorded,
    'alert_count', cardinality(coalesce(p_alert_keys, ARRAY[]::text[]))
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.record_valu_reconciliation_health_snapshot(jsonb, text[]) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.record_valu_reconciliation_health_snapshot(jsonb, text[]) TO service_role;
